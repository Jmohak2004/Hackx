const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "..");
const artifactPath = path.join(root, "artifacts/contracts/LatentStyleGame.sol/LatentStyleGame.json");

function exportContract() {
  if (!fs.existsSync(artifactPath)) throw new Error("Compile first: npm run contracts:compile");
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  const output = { contractName: artifact.contractName, version: 2, abi: artifact.abi };
  fs.writeFileSync(path.join(root, "server/game-artifact.json"), JSON.stringify(output, null, 2) + "\n");
  fs.writeFileSync(
    path.join(root, "client/lib/game-abi.ts"),
    "// Generated by npm run contracts:export; edit contracts/LatentStyleGame.sol.\n" +
    "export const GAME_ABI = " + JSON.stringify(artifact.abi, null, 2) + " as const;\n"
  );
  return output;
}
if (require.main === module) exportContract();
module.exports = { exportContract };
